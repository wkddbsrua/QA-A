# -*- coding: utf-8 -*-
"""판 번호가 있는 단 하나의 자리.

★같은 이름으로 덮어쓰지 않는다. "지난번 exe 와 이번 exe 중 어느 것을 쓰고 있나" 를
  가릴 수 없어서 "이전에는 됐는데" 라는 보고를 재현조차 못 한 일이 있었다.
  파일 이름(release/*.exe · 추출 .md)과 화면 표시(창 머리·브라우저 툴바)와 전달 문서에
  모두 같은 번호가 나가야 그 보고가 진단이 된다.

VERSION 은 사람이 올린다(동작이 바뀔 때).  BUILD 는 build_exe.py 가 빌드마다 올린다 -
사람이 손으로 올리면 반드시 잊는다.
"""

VERSION = '1.0'
BUILD = 1     # 0 = build_exe.py 를 거치지 않은 소스


def label():
    """사람이 읽는 표기. 창·툴바·문서에 같은 문자열이 나간다."""
    return u'v%s (%03d)' % (VERSION, BUILD)


def slug():
    """파일 이름에 붙이는 표기. 공백·괄호를 쓰지 않는다(경로가 깨진다)."""
    return u'v%s_%03d' % (VERSION, BUILD)
